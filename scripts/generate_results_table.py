import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import torch
from sklearn.metrics import roc_auc_score
from torch.utils.data import DataLoader

from src.config import (
    IMAGE_SIZE,
    KAGGLE_DIR,
    MODEL_DIR,
    NIH_DIR,
    OPENI_DIR,
    ROOT,
    SEED,
    get_device,
)
from src.data.dataset import ChestXrayDataset, get_transforms
from src.data.nih import build_nih_manifest
from src.data.openi import build_openi_manifest
from src.data.split import build_manifest, patient_level_split
from src.eval.domain_shift import evaluate_across_datasets
from src.eval.stats import bootstrap_ci, sensitivity_at_threshold
from src.models import MODEL_REGISTRY

RESULTS_PATH = ROOT / "docs" / "results.md"


def build_loaders(batch_size: int, num_workers: int, nih_sample_size):
    kaggle_manifest = build_manifest(KAGGLE_DIR)
    _train_df, _val_df, kaggle_test_df = patient_level_split(kaggle_manifest, seed=SEED)
    kaggle_test_ds = ChestXrayDataset(kaggle_test_df, transform=get_transforms(IMAGE_SIZE, train=False))

    nih_manifest = build_nih_manifest(NIH_DIR)
    if nih_sample_size is not None and nih_sample_size < len(nih_manifest):
        nih_manifest = nih_manifest.sample(n=nih_sample_size, random_state=SEED).reset_index(drop=True)
    nih_ds = ChestXrayDataset(nih_manifest, transform=get_transforms(IMAGE_SIZE, train=False))

    openi_manifest = build_openi_manifest(OPENI_DIR)
    openi_ds = ChestXrayDataset(openi_manifest, transform=get_transforms(IMAGE_SIZE, train=False))

    return {
        "kaggle_test": DataLoader(
            kaggle_test_ds, batch_size=batch_size, shuffle=False, num_workers=num_workers
        ),
        "nih": DataLoader(nih_ds, batch_size=batch_size, shuffle=False, num_workers=num_workers),
        "openi": DataLoader(openi_ds, batch_size=batch_size, shuffle=False, num_workers=num_workers),
    }


def render_markdown_table(all_results: dict, n_boot: int) -> str:
    lines = [
        "# Results",
        "",
        "Auto-generated by `scripts/generate_results_table.py` -- do not hand-edit.",
        "",
        "| Model | Dataset | n | Accuracy | Precision | Recall | F1 | AUC-ROC | AUC-ROC 95% CI | Sensitivity 95% CI |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    sens_fn = sensitivity_at_threshold(0.5)
    for model_name, dataset_results in all_results.items():
        for dataset_name, result in dataset_results.items():
            m = result["metrics"]
            n = len(result["y_true"])
            _point, auc_lo, auc_hi = bootstrap_ci(
                result["y_true"], result["y_prob"], roc_auc_score, n_boot=n_boot
            )
            _point, sens_lo, sens_hi = bootstrap_ci(
                result["y_true"], result["y_prob"], sens_fn, n_boot=n_boot
            )
            lines.append(
                f"| {model_name} | {dataset_name} | {n} | {m['accuracy']:.3f} | {m['precision']:.3f} | "
                f"{m['recall']:.3f} | {m['f1']:.3f} | {m['auc_roc']:.3f} | "
                f"{auc_lo:.3f}-{auc_hi:.3f} | {sens_lo:.3f}-{sens_hi:.3f} |"
            )
    lines.append("")
    return "\n".join(lines)


def main(batch_size: int, num_workers: int, nih_sample_size, n_boot: int):
    device = get_device()
    loaders = build_loaders(batch_size, num_workers, nih_sample_size)

    available_models = [name for name in MODEL_REGISTRY if (MODEL_DIR / f"{name}.pt").exists()]
    if not available_models:
        print(f"No trained checkpoints found in {MODEL_DIR}. Run scripts/train.py first.")
        return

    all_results = {}
    for model_name in available_models:
        print(f"Evaluating {model_name}...")
        model = MODEL_REGISTRY[model_name]()
        model.load_state_dict(torch.load(MODEL_DIR / f"{model_name}.pt", map_location=device))
        model.to(device)
        all_results[model_name] = evaluate_across_datasets(model, loaders, device)

    print("Computing bootstrapped 95% CIs...")
    table = render_markdown_table(all_results, n_boot)
    RESULTS_PATH.write_text(table)
    print(f"\nWrote {RESULTS_PATH}")
    print(table)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--num-workers", type=int, default=8)
    parser.add_argument(
        "--nih-sample-size",
        type=int,
        default=None,
        help="Evaluate on a random sample of NIH instead of all 61k+ examples. Omit for the full set.",
    )
    parser.add_argument(
        "--n-boot", type=int, default=1000, help="Bootstrap resamples for confidence intervals."
    )
    args = parser.parse_args()
    main(args.batch_size, args.num_workers, args.nih_sample_size, args.n_boot)
