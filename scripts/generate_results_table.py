import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import torch
from sklearn.metrics import roc_auc_score
from torch.utils.data import DataLoader

from src.config import (
    IMAGE_SIZE,
    KAGGLE_DIR,
    MODEL_DIR,
    NIH_DIR,
    OPENI_DIR,
    ROOT,
    SEED,
    get_device,
)
from src.data.dataset import ChestXrayDataset, get_transforms
from src.data.nih import build_nih_manifest
from src.data.openi import build_openi_manifest
from src.data.split import build_manifest, parse_patient_id, patient_level_split
from src.eval.calibration import brier_score, expected_calibration_error
from src.eval.domain_shift import evaluate_across_datasets
from src.eval.stats import bootstrap_ci, bootstrap_ci_clustered, sensitivity_at_threshold
from src.models import MODEL_REGISTRY

RESULTS_PATH = ROOT / "docs" / "results.md"


def build_loaders(batch_size: int, num_workers: int, nih_sample_size):
    """Returns (loaders, groups): groups[name] is a patient/study-ID array
    aligned with each loader's (shuffle=False) iteration order, or None
    where no grouping key is available, for the clustered bootstrap CI.
    """
    kaggle_manifest = build_manifest(KAGGLE_DIR)
    _train_df, _val_df, kaggle_test_df = patient_level_split(kaggle_manifest, seed=SEED)
    kaggle_test_ds = ChestXrayDataset(kaggle_test_df, transform=get_transforms(IMAGE_SIZE, train=False))
    kaggle_groups = kaggle_test_df["path"].apply(lambda p: parse_patient_id(Path(p).name)).tolist()

    nih_manifest = build_nih_manifest(NIH_DIR)
    if nih_sample_size is not None and nih_sample_size < len(nih_manifest):
        nih_manifest = nih_manifest.sample(n=nih_sample_size, random_state=SEED).reset_index(drop=True)
    nih_ds = ChestXrayDataset(nih_manifest, transform=get_transforms(IMAGE_SIZE, train=False))
    nih_groups = nih_manifest["Patient ID"].tolist() if "Patient ID" in nih_manifest.columns else None

    openi_manifest = build_openi_manifest(OPENI_DIR)
    openi_ds = ChestXrayDataset(openi_manifest, transform=get_transforms(IMAGE_SIZE, train=False))
    openi_groups = openi_manifest["study_id"].tolist() if "study_id" in openi_manifest.columns else None

    loaders = {
        "kaggle_test": DataLoader(
            kaggle_test_ds, batch_size=batch_size, shuffle=False, num_workers=num_workers
        ),
        "nih": DataLoader(nih_ds, batch_size=batch_size, shuffle=False, num_workers=num_workers),
        "openi": DataLoader(openi_ds, batch_size=batch_size, shuffle=False, num_workers=num_workers),
    }
    groups = {"kaggle_test": kaggle_groups, "nih": nih_groups, "openi": openi_groups}
    return loaders, groups


def _bootstrap(result: dict, dataset_groups, fn, n_boot: int):
    if dataset_groups is not None:
        return bootstrap_ci_clustered(result["y_true"], result["y_prob"], dataset_groups, fn, n_boot=n_boot)
    return bootstrap_ci(result["y_true"], result["y_prob"], fn, n_boot=n_boot)


def render_markdown_table(all_results: dict, groups: dict, n_boot: int) -> str:
    lines = [
        "# Results",
        "",
        "Auto-generated by `scripts/generate_results_table.py` -- do not hand-edit.",
        "",
        "AUC-ROC alone is misleading at NIH/OpenI's low pneumonia prevalence "
        "(a few percent) -- AUPRC is reported alongside it for that reason. "
        "Confidence intervals are patient/study-level (clustered) bootstraps "
        "where a grouping key is available (Kaggle, NIH, OpenI), example-level "
        "otherwise; see `src/eval/stats.bootstrap_ci_clustered`.",
        "",
        "## Discrimination and threshold metrics",
        "",
        "| Model | Dataset | n | Accuracy | Precision (PPV) | Recall (Sens.) | "
        "Specificity | NPV | Balanced Acc. | F1 | AUC-ROC | AUPRC |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for model_name, dataset_results in all_results.items():
        for dataset_name, result in dataset_results.items():
            m = result["metrics"]
            n = len(result["y_true"])
            lines.append(
                f"| {model_name} | {dataset_name} | {n} | {m['accuracy']:.3f} | {m['precision']:.3f} | "
                f"{m['recall']:.3f} | {m['specificity']:.3f} | {m['npv']:.3f} | "
                f"{m['balanced_accuracy']:.3f} | {m['f1']:.3f} | {m['auc_roc']:.3f} | {m['auprc']:.3f} |"
            )

    lines += [
        "",
        "## Calibration and confidence intervals",
        "",
        "| Model | Dataset | AUC-ROC 95% CI | Sensitivity 95% CI | Brier score | ECE |",
        "|---|---|---|---|---|---|",
    ]
    sens_fn = sensitivity_at_threshold(0.5)
    for model_name, dataset_results in all_results.items():
        for dataset_name, result in dataset_results.items():
            dataset_groups = groups.get(dataset_name)
            _point, auc_lo, auc_hi = _bootstrap(result, dataset_groups, roc_auc_score, n_boot)
            _point, sens_lo, sens_hi = _bootstrap(result, dataset_groups, sens_fn, n_boot)
            brier = brier_score(result["y_true"], result["y_prob"])
            ece = expected_calibration_error(result["y_true"], result["y_prob"])
            lines.append(
                f"| {model_name} | {dataset_name} | {auc_lo:.3f}-{auc_hi:.3f} | "
                f"{sens_lo:.3f}-{sens_hi:.3f} | {brier:.3f} | {ece:.3f} |"
            )
    lines.append("")
    return "\n".join(lines)


def main(batch_size: int, num_workers: int, nih_sample_size, n_boot: int):
    device = get_device()
    loaders, groups = build_loaders(batch_size, num_workers, nih_sample_size)

    available_models = [name for name in MODEL_REGISTRY if (MODEL_DIR / f"{name}.pt").exists()]
    if not available_models:
        print(f"No trained checkpoints found in {MODEL_DIR}. Run scripts/train.py first.")
        return

    all_results = {}
    for model_name in available_models:
        print(f"Evaluating {model_name}...")
        model = MODEL_REGISTRY[model_name]()
        model.load_state_dict(torch.load(MODEL_DIR / f"{model_name}.pt", map_location=device))
        model.to(device)
        all_results[model_name] = evaluate_across_datasets(model, loaders, device)

    print("Computing bootstrapped 95% CIs...")
    table = render_markdown_table(all_results, groups, n_boot)
    RESULTS_PATH.write_text(table)
    print(f"\nWrote {RESULTS_PATH}")
    print(table)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--num-workers", type=int, default=8)
    parser.add_argument(
        "--nih-sample-size",
        type=int,
        default=None,
        help="Evaluate on a random sample of NIH instead of all 61k+ examples. Omit for the full set.",
    )
    parser.add_argument(
        "--n-boot", type=int, default=1000, help="Bootstrap resamples for confidence intervals."
    )
    args = parser.parse_args()
    main(args.batch_size, args.num_workers, args.nih_sample_size, args.n_boot)
